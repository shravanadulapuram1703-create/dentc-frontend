/**
 * FE <-> BE API drift report.
 *
 * Scans every hand-written service file for axios calls (method + URL),
 * normalizes dynamic `${...}` segments, and checks each (method, path) pair
 * against the committed openapi.json. Emits a per-feature Markdown report.
 *
 *   node scripts/api-drift-report.mjs            # writes docs/API_DRIFT_REPORT.md
 *   node scripts/api-drift-report.mjs --stdout   # also prints a summary
 */
import fs from "node:fs";
import path from "node:path";

const s = JSON.parse(fs.readFileSync("./openapi.json", "utf8"));

// (method, path) existence + path-only existence (for method-mismatch detection)
const methodPaths = new Set();
const pathOnly = [];
for (const [p, ms] of Object.entries(s.paths)) {
  const re = new RegExp("^" + p.replace(/\{[^}]+\}/g, "{}") + "$");
  pathOnly.push(re);
  for (const m of Object.keys(ms)) methodPaths.add(`${m.toLowerCase()} ${p.replace(/\{[^}]+\}/g, "{}")}`);
}
// path-template ({} normalized) -> set of methods the backend supports
const methodsForPath = {};
for (const [p, ms] of Object.entries(s.paths)) {
  const np = p.replace(/\{[^}]+\}/g, "{}");
  methodsForPath[np] = Object.keys(ms).map((m) => m.toUpperCase());
}
const normalize = (url) =>
  url
    .replace(/\$\{[^}]*\}/g, "{}") // template expr -> {}
    .replace(/\{[^}]+\}/g, "{}") // any {named} -> {}
    .replace(/\?.*$/, "") // drop query string
    .replace(/\/+$/, "");
const pathExists = (np) => pathOnly.some((re) => re.test(np));
const methodPathExists = (m, np) => methodPaths.has(`${m} ${np}`);

// Map service file -> feature/screen (for grouping in the report).
const FEATURE = {
  "authService.ts": "Auth",
  "userApi.ts": "Users / Staff setup",
  "patientApi.ts": "Patients (search / CRUD)",
  "patient.service.ts": "Patients (search / CRUD)",
  "patientMetadataApi.ts": "Patient metadata (dropdowns)",
  "ledgerApi.ts": "Patient Ledger / Billing",
  "schedulerApi.ts": "Scheduler / Appointments",
  "organizationApi.ts": "Organization / Access",
  "accountSetupApi.ts": "Account setup",
  "feeSchedules.ts": "Fee schedules",
};

const dirs = ["src/services", "src/api"];
const files = [];
for (const d of dirs) {
  if (!fs.existsSync(d)) continue;
  for (const f of fs.readdirSync(d)) if (f.endsWith(".ts") && f !== ".ts") files.push(path.join(d, f));
}

// api.<method><Generics?>( `url` | "url" | 'url'
const callRe =
  /\bapi\.(get|post|put|patch|delete)\s*(?:<[^>]*>)?\s*\(\s*([`'"])(\/api\/v1\/[^`'"]*)\2/g;

const rows = [];
for (const f of files) {
  const base = path.basename(f);
  const txt = fs.readFileSync(f, "utf8");
  let m;
  while ((m = callRe.exec(txt))) {
    const method = m[1].toLowerCase();
    const raw = m[3];
    const np = normalize(raw);
    const exists = pathExists(np);
    const methodOk = methodPathExists(method, np);
    rows.push({
      file: base,
      feature: FEATURE[base] ?? base,
      method: method.toUpperCase(),
      url: raw,
      np,
      status: !exists ? "MISSING" : !methodOk ? "METHOD-MISMATCH" : "OK",
    });
  }
}

// De-dup identical (method, np)
const seen = new Set();
const uniq = rows.filter((r) => {
  const k = `${r.method} ${r.np} ${r.file}`;
  if (seen.has(k)) return false;
  seen.add(k);
  return true;
});

const byFeature = {};
for (const r of uniq) (byFeature[r.feature] = byFeature[r.feature] || []).push(r);

const total = uniq.length;
const missing = uniq.filter((r) => r.status === "MISSING").length;
const mismatch = uniq.filter((r) => r.status === "METHOD-MISMATCH").length;
const ok = total - missing - mismatch;

const icon = { OK: "✅", MISSING: "❌", "METHOD-MISMATCH": "⚠️" };
let md = `# Frontend ↔ Backend API Drift Report

> Auto-generated by \`scripts/api-drift-report.mjs\` from \`openapi.json\` (FastAPI \`${s.info?.title} v${s.info?.version}\`, ${Object.keys(s.paths).length} paths).
> Regenerate after every \`npm run api:fetch\`.

## Summary

| | Count |
|---|---|
| Endpoints called by the frontend | **${total}** |
| ✅ Present (path + method) | **${ok}** |
| ⚠️ Path exists, method differs | **${mismatch}** |
| ❌ Absent from backend | **${missing}** |

**${Math.round((missing / total) * 100)}%** of the endpoints the frontend calls do not exist on the current backend. This indicates the UI was built against a different/older API contract (see \`docs/api-contracts/\`). Features whose endpoints are entirely missing are non-functional against this backend.

`;

for (const [feat, list] of Object.entries(byFeature).sort()) {
  const miss = list.filter((r) => r.status !== "OK").length;
  const tag = miss === 0 ? "fully covered ✅" : miss === list.length ? "**no backend coverage ❌**" : `partial (${list.length - miss}/${list.length}) ⚠️`;
  md += `### ${feat} — ${tag}\n\n| | Method | Endpoint |\n|---|---|---|\n`;
  for (const r of list.sort((a, b) => a.url.localeCompare(b.url))) {
    const note =
      r.status === "METHOD-MISMATCH"
        ? ` — backend: ${(methodsForPath[r.np] || []).join("/")}`
        : "";
    md += `| ${icon[r.status]} | ${r.method}${note} | \`${r.url}\` |\n`;
  }
  md += `\n`;
}

md += `## Legend

- ✅ **OK** — path and HTTP method both exist in the schema.
- ⚠️ **METHOD-MISMATCH** — the path exists but under a different HTTP method (e.g. backend uses \`PATCH\`, frontend uses \`PUT\`).
- ❌ **MISSING** — no matching path in the schema; the backend does not serve this route.

> Note: dynamic URLs are normalized (\`\${id}\` → \`{}\`) and query strings dropped before matching. URLs built from variables (not string literals) may be undercounted.
`;

fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/API_DRIFT_REPORT.md", md);
console.log(`Wrote docs/API_DRIFT_REPORT.md — ${total} endpoints: ${ok} ok, ${mismatch} method-mismatch, ${missing} missing.`);

if (process.argv.includes("--stdout")) {
  for (const [feat, list] of Object.entries(byFeature).sort()) {
    const miss = list.filter((r) => r.status !== "OK").length;
    console.log(`  ${feat}: ${list.length - miss}/${list.length} present`);
  }
}
