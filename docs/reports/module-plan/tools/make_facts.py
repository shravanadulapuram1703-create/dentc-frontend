"""Generate plan_inputs/facts.md: the counts the plan documents quote (reports, controls, metrics, dashboards, work items).

Usage: python -I make_facts.py <plan_root>

Run after collect_work_items.py and render_parity_matrix.py. Every number in 10-12 and README must come from here.
"""
import collections
import json
import os
import re
import sys


def main(root):
    P = lambda *a: os.path.join(root, *a)
    L = ['# Facts - generated counts', '', 'Generated by `tools/make_facts.py`. Quote numbers from here only; regenerate after any change.', '']
    # legacy parity
    cats = []
    tot = collections.Counter()
    for f in sorted(os.listdir(P('legacy', 'index'))):
        if not f.endswith('.controls.json'):
            continue
        idx = json.load(open(P('legacy', 'index', f), encoding='utf-8'))
        pp = P('catalog', 'parity', idx['category'] + '.parity.json')
        par = json.load(open(pp, encoding='utf-8')) if os.path.exists(pp) else {'reports': []}
        st = collections.Counter(c.get('status') for r in par['reports'] for c in r['controls'])
        ph = collections.Counter(r.get('phase') for r in par['reports'])
        rules = sum(len(r.get('dynamic_rules', [])) for r in idx['reports'])
        row = (idx['category'], len(idx['reports']), idx.get('screenshot_control_count', 0), idx.get('vendor_doc_control_count', 0),
               idx['control_count'], rules, st, ph)
        cats.append(row)
        tot.update({'reports': row[1], 'shot': row[2], 'vendor': row[3], 'controls': row[4], 'rules': rules})
        for k, v in st.items():
            tot['st_' + str(k)] += v
        for k, v in ph.items():
            tot['ph_' + str(k)] += v
    L += ['## Legacy parity', '',
          f'- Categories: {len(cats)}; legacy reports: {tot["reports"]}',
          f'- Criteria controls: {tot["controls"]} ({tot["shot"]} read from screenshots + {tot["vendor"]} added from vendor documentation)',
          f'- Documented show/hide/enable rules: {tot["rules"]}',
          '- Control status: ' + ', '.join(f'{k[3:]}={v}' for k, v in sorted(tot.items()) if k.startswith('st_')),
          '- Legacy reports per phase: ' + ', '.join(f'{k[3:]}={v}' for k, v in sorted(tot.items()) if k.startswith('ph_')), '',
          '| Category | Reports | Controls (screenshot + vendor doc) | Rules | Reports per phase |', '|---|---|---|---|---|']
    for c, n, s, v, t, ru, st, ph in cats:
        L.append(f'| {c} | {n} | {t} ({s} + {v}) | {ru} | {", ".join(f"{k}={x}" for k, x in sorted(ph.items()))} |')
    # new analytics reports
    ap = P('catalog', 'analytics_reports.md')
    if os.path.exists(ap):
        txt = open(ap, encoding='utf-8').read()
        keys = re.findall(r'^## .+ - `([a-z_]+\.[a-z0-9_]+)`', txt, re.M)
        L += ['', '## New analytics reports (catalog/analytics_reports.md)', '', f'- New reports: {len(keys)}']
    else:
        L += ['', '## New analytics reports', '', '- catalog/analytics_reports.md not written yet']
    # metrics and dashboards
    mc = open(P('05_metric_catalog.md'), encoding='utf-8').read()
    mkeys = set(re.findall(r'^\| `([a-z][a-z0-9_]*)` \|', mc, re.M))
    dc = open(P('06_dashboards.md'), encoding='utf-8').read()
    dkeys = re.findall(r'^### 2\.\d+ .+ — `(dashboards\.[a-z_]+)`', dc, re.M)
    L += ['', '## Metrics and dashboards', '', f'- Metric keys in 05_metric_catalog.md: {len(mkeys)}',
          f'- Dashboards in 06_dashboards.md: {len(dkeys)} ({", ".join(dkeys)})']
    # work items
    wi = json.load(open(P('work_items.json'), encoding='utf-8'))
    items = wi['items']
    by_ph = collections.Counter(i['phase_id'] for i in items)
    by_area = collections.defaultdict(collections.Counter)
    for i in items:
        by_area[i['area']][i['phase_id']] += 1
    phases = sorted(by_ph)
    w = {'S': 1, 'M': 3, 'L': 8, 'XL': 15}
    eff = collections.Counter()
    for i in items:
        eff[i['phase_id']] += w.get(i.get('size_id'), 0)
    L += ['', '## Work items (work_items.json)', '', f'- Total: {len(items)}; register problems: {len(wi.get("problems", []))}',
          '- Per phase: ' + ', '.join(f'{p}={by_ph[p]}' for p in phases),
          '- Relative effort points per phase (S=1, M=3, L=8, XL=15): ' + ', '.join(f'{p}={eff[p]}' for p in phases), '',
          '| Area | ' + ' | '.join(phases) + ' | Total |', '|---|' + '---|' * (len(phases) + 1)]
    for a in sorted(by_area):
        L.append(f'| {a} | ' + ' | '.join(str(by_area[a][p] or '') for p in phases) + f' | {sum(by_area[a].values())} |')
    probs = wi.get('problems', [])
    if probs:
        L += ['', '## Register problems the plans must resolve', '',
              'A phase inversion means a work item depends on an item scheduled in a later phase: the plan either moves the dependency',
              'earlier or the dependent later, and says which.', '']
        L += [f'- {p}' if isinstance(p, str) else f'- {json.dumps(p, ensure_ascii=False)}' for p in probs]
    heavy = max(by_ph, key=lambda p: eff[p])
    L += ['', '## Load note', '', f'- Heaviest phase by effort points: {heavy} ({eff[heavy]} points, {by_ph[heavy]} items). '
          'The roadmap should consider splitting it into waves.']
    os.makedirs(P('plan_inputs'), exist_ok=True)
    open(P('plan_inputs', 'facts.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'wrote plan_inputs/facts.md: reports={tot["reports"]} controls={tot["controls"]} metrics={len(mkeys)} dashboards={len(dkeys)} work_items={len(items)}')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main(sys.argv[1])
