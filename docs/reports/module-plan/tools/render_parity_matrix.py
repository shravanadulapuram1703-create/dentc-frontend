"""Generate the parity matrix: the proof that every legacy report and control is mapped.

Usage: python -I render_parity_matrix.py <legacy/index> <catalog/parity> <out.md>

For every category it re-runs the parity check, then writes one document with: totals per category and
status, every report with its report_key and phase, every control that is NOT replicated one-to-one (with
the reason), deliberately changed defaults, action-button mappings, the canonical parameters with their
usage, the criteria added from vendor documentation (controls, option values, show/hide/enable rules) and
the legacy screens that still need confirming on the live tool.
"""
import contextlib
import io
import json
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import validate_parity  # noqa: E402

ORDER = ['daily_reports', 'montly_reports', 'ledger_reports', 'management_reports', 'insurance_reports',
         'appointment_reports', 'treatmentplan_reports', 'refferal_reports', 'recall_reports', 'ortho_reports',
         'statements_reports', 'patients_list_reports', 'providers_list_reports', 'security_list_reports',
         'setup_list_reports', 'my_reports']
TITLES = {'daily_reports': 'Daily Reports', 'montly_reports': 'Monthly Reports', 'ledger_reports': 'Ledger Reports',
          'management_reports': 'Management Reports', 'insurance_reports': 'Insurance Reports',
          'appointment_reports': 'Appointment Reports', 'treatmentplan_reports': 'Treatment Plan Reports',
          'refferal_reports': 'Referral Reports', 'recall_reports': 'Recall Reports', 'ortho_reports': 'Ortho Reports',
          'statements_reports': 'Statements', 'patients_list_reports': 'Lists - Patient',
          'providers_list_reports': 'Lists - Provider', 'security_list_reports': 'Lists - Security',
          'setup_list_reports': 'Lists - Setup', 'my_reports': 'My Reports'}
DOCS = {'daily_reports': 'daily_reports.md', 'montly_reports': 'monthly_reports.md', 'ledger_reports': 'ledger_reports.md',
        'management_reports': 'management_reports.md', 'insurance_reports': 'insurance_reports.md',
        'appointment_reports': 'appointment_reports.md', 'treatmentplan_reports': 'treatment_plan_reports.md',
        'refferal_reports': 'referral_reports.md', 'recall_reports': 'recall_reports.md', 'ortho_reports': 'ortho_reports.md',
        'statements_reports': 'statements.md', 'patients_list_reports': 'patient_lists.md',
        'providers_list_reports': 'provider_lists.md', 'security_list_reports': 'security_lists.md',
        'setup_list_reports': 'setup_lists.md', 'my_reports': 'my_reports.md'}
STATUSES = ['replicated', 'replicated_enhanced', 'help_text', 'superseded', 'not_applicable', 'unknown_legacy']


def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def esc(s):
    return norm(s).replace('|', '\\|')


def code(s):
    return ('`' + esc(s) + '`') if norm(s) else '-'


def main(index_dir, parity_dir, out):
    L = ['# Parity matrix - every legacy report and control, mapped', '',
         'Generated by `tools/render_parity_matrix.py` from `legacy/index/*.controls.json` (the verified legacy',
         'inventory: what our screenshots show plus what vendor documentation adds) and `catalog/parity/*.parity.json`',
         '(the mapping written with each report specification). Regenerate it after any change; do not edit by hand.', '']
    rows, reports, odd, changed_defaults = [], [], [], []
    vendor_controls, vendor_options, rules, corrections, unresolved = [], [], [], [], []
    actions = defaultdict(set)
    params = defaultdict(lambda: {'controls': 0, 'reports': set(), 'types': set()})
    truncated, unreadable = [], []
    tot = defaultdict(int)
    all_valid = True
    for cat in ORDER:
        ip = os.path.join(index_dir, cat + '.controls.json')
        pp = os.path.join(parity_dir, cat + '.parity.json')
        if not os.path.exists(ip):
            continue
        idx = json.load(open(ip, encoding='utf-8'))
        n_rep, n_ctl = idx['report_count'], idx['control_count']
        n_vendor = sum(1 for r in idx['reports'] for c in r['controls'] if c.get('origin') == 'vendor_doc')
        n_rules = sum(len(r.get('dynamic_rules', [])) for r in idx['reports'])
        for r in idx['reports']:
            if r.get('possibly_truncated'):
                truncated.append((TITLES[cat], r['name'], norm(r.get('notes'))))
            for k in r.get('corrections', []):
                corrections.append((TITLES[cat], r['name'], k.get('about'), k.get('text'), k.get('confidence')))
            for c in r['controls']:
                if '[?]' in ' '.join([c['section'], c['label'], ' '.join(c['options']), c['default_value']]):
                    unreadable.append((TITLES[cat], r['name'], c['section'], c['label'], norm(c['notes'])))
        for u in idx.get('supplement_unresolved', []):
            name = next((r['name'] for r in idx['reports'] if r['report_id'] == u.get('report_id')), '')
            unresolved.append((TITLES[cat], name, u.get('question')))
        tot['reports'] += n_rep
        tot['controls'] += n_ctl
        tot['vendor'] += n_vendor
        tot['rules'] += n_rules
        if not os.path.exists(pp):
            rows.append((cat, n_rep, n_ctl, n_vendor, n_rules, {}, 'MISSING'))
            all_valid = False
            continue
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = validate_parity.main(ip, pp)
        verdict = 'VALID' if rc == 0 else 'INVALID'
        all_valid = all_valid and rc == 0
        par = json.load(open(pp, encoding='utf-8'))
        icontrols = {c['control_id']: (r['name'], c) for r in idx['reports'] for c in r['controls']}
        irules = {d['rule_id']: (r['name'], d) for r in idx['reports'] for d in r.get('dynamic_rules', [])}
        counts = defaultdict(int)
        for pr in par.get('reports', []):
            reports.append((TITLES[cat], pr.get('legacy_name'), pr.get('report_key'), pr.get('phase'), len(pr.get('controls', [])), DOCS[cat]))
            for a in pr.get('actions', []):
                actions[norm(a.get('legacy_action')).upper()].add(norm(a.get('new_feature')))
            for d in pr.get('dynamic_rules', []):
                rname, idr = irules.get(d.get('rule_id'), (pr.get('legacy_name'), {}))
                rules.append((TITLES[cat], rname, idr.get('when'), idr.get('effect'), idr.get('confidence'), d.get('new_behavior')))
            for c in pr.get('controls', []):
                st = c.get('status')
                counts[st] += 1
                rname, ic = icontrols.get(c.get('control_id'), (pr.get('legacy_name'), {}))
                if norm(c.get('param')):
                    p = params[c['param']]
                    p['controls'] += 1
                    p['reports'].add(pr.get('report_key'))
                    p['types'].add(norm(c.get('param_type')))
                if st not in ('replicated', 'replicated_enhanced'):
                    odd.append((TITLES[cat], rname, c.get('legacy_section'), c.get('legacy_label'), st, c.get('param'), norm(c.get('notes'))))
                if norm(c.get('default_differs_reason')):
                    changed_defaults.append((TITLES[cat], rname, c.get('legacy_section'), c.get('legacy_label'),
                                             norm(ic.get('default_value')), c.get('default'), norm(c.get('default_differs_reason'))))
                if ic.get('origin') == 'vendor_doc':
                    vendor_controls.append((TITLES[cat], rname, ic.get('section'), ic.get('label'), ic.get('type'),
                                            ' / '.join(ic.get('options', [])), ic.get('confidence'), c.get('param'), st))
                if ic.get('vendor_doc_options'):
                    om = {norm(k): v for k, v in (c.get('option_map') or {}).items()}
                    vendor_options.append((TITLES[cat], rname, ic.get('section'), ic.get('label'),
                                           ', '.join(f'{o} -> `{om.get(norm(o), "?")}`' for o in ic['vendor_doc_options']),
                                           ic.get('vendor_doc_options_confidence'), c.get('param')))
        for s in STATUSES:
            tot[s] += counts[s]
        rows.append((cat, n_rep, n_ctl, n_vendor, n_rules, counts, verdict))

    L += [f'**Result:** {"every category passes the parity check" if all_valid else "NOT ALL CATEGORIES PASS - see the Check column"}. '
          f'{tot["reports"]} reports and {tot["controls"]} legacy criteria controls are mapped '
          f'({tot["controls"] - tot["vendor"]} read from our screenshots, {tot["vendor"]} added from vendor documentation): '
          f'{tot["replicated"]} replicated as they are, {tot["replicated_enhanced"]} replicated with additions, '
          f'{tot["help_text"]} kept as help text, {tot["superseded"]} superseded by an equivalent, '
          f'{tot["not_applicable"]} not applicable, {tot["unknown_legacy"]} awaiting confirmation on the legacy tool. '
          f'{tot["rules"]} documented show / hide / enable rules are mapped as well.', '']
    L += ['## 1. Totals by category', '',
          '| Category | Reports | Controls | of which from vendor documentation | Rules | Replicated | Replicated + additions | Help text | Superseded | Not applicable | To confirm | Check | Specification |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for cat, n_rep, n_ctl, n_vendor, n_rules, counts, verdict in rows:
        L.append(f'| {TITLES[cat]} | {n_rep} | {n_ctl} | {n_vendor} | {n_rules} | ' + ' | '.join(str(counts.get(s, 0)) for s in STATUSES)
                 + f' | {verdict} | [catalog/{DOCS[cat]}](catalog/{DOCS[cat]}) |')
    L.append(f'| **Total** | **{tot["reports"]}** | **{tot["controls"]}** | **{tot["vendor"]}** | **{tot["rules"]}** | '
             + ' | '.join(f'**{tot[s]}**' for s in STATUSES) + ' | | |')
    L.append('')

    L += ['## 2. Every legacy report and its new key', '', '| Category | Legacy report | report_key | Phase | Controls | Specification |', '|---|---|---|---|---|---|']
    for cat, name, key, phase, n, doc in reports:
        L.append(f'| {cat} | {esc(name)} | `{esc(key)}` | {esc(phase)} | {n} | [catalog/{doc}](catalog/{doc}) |')
    L.append('')

    L += ['## 3. Controls not replicated one-to-one', '',
          'Everything that is not a plain replication, with the reason. "unknown_legacy" means the legacy control could not be read from the screenshot or the vendor documentation.', '',
          '| Category | Report | Legacy section | Legacy control | Status | Parameter | Reason |', '|---|---|---|---|---|---|---|']
    for cat, rname, sec, label, st, param, notes in odd:
        L.append(f'| {cat} | {esc(rname)} | {esc(sec)} | {esc(label) or "(no label)"} | {esc(st)} | {code(param)} | {esc(notes)} |')
    L.append('')

    L += ['## 4. Defaults that deliberately differ from the legacy default', '',
          '| Category | Report | Legacy section | Legacy control | Legacy default | New default | Reason |', '|---|---|---|---|---|---|---|']
    for cat, rname, sec, label, ld, nd, why in changed_defaults:
        L.append(f'| {cat} | {esc(rname)} | {esc(sec)} | {esc(label) or "(no label)"} | {esc(ld)} | `{esc(json.dumps(nd) if not isinstance(nd, str) else nd)}` | {esc(why)} |')
    if not changed_defaults:
        L.append('| - | none | | | | | |')
    L.append('')

    L += ['## 5. Legacy action buttons', '', '| Legacy button | In the new module |', '|---|---|']
    for a, feats in sorted(actions.items()):
        L.append(f'| {esc(a)} | {esc(" / ".join(sorted(f for f in feats if f)))} |')
    L.append('')

    L += ['## 6. Parameters and where they are used', '', '| Parameter | Type | Controls mapped | Reports |', '|---|---|---|---|']
    for p, v in sorted(params.items(), key=lambda kv: (-kv[1]['controls'], kv[0])):
        L.append(f'| `{esc(p)}` | {esc(", ".join(sorted(t for t in v["types"] if t)))} | {v["controls"]} | {len(v["reports"])} |')
    L.append('')

    L += ['## 7. Criteria added from vendor documentation', '',
          'Our screenshots show each criteria screen in one state only. Vendor documentation shows rows hidden below the',
          'captured area, values of collapsed dropdowns and criteria that only appear in another mode. They are part of',
          'the checklist; "confirmed" = shown or stated by the vendor, "likely" = implied by vendor text.', '',
          '### 7.1 Controls our screenshots do not show', '',
          '| Category | Report | Legacy section | Legacy control | Type | Options | Evidence | Parameter | Status |', '|---|---|---|---|---|---|---|---|---|']
    for cat, rname, sec, label, typ, opts, conf, param, st in vendor_controls:
        L.append(f'| {cat} | {esc(rname)} | {esc(sec)} | {esc(label) or "(no label)"} | {esc(typ)} | {esc(opts) or "-"} | {esc(conf)} | {code(param)} | {esc(st)} |')
    if not vendor_controls:
        L.append('| - | none | | | | | | | |')
    L += ['', '### 7.2 Option values our screenshots do not show', '',
          '| Category | Report | Legacy section | Legacy control | Added values and their new value | Evidence | Parameter |', '|---|---|---|---|---|---|---|']
    for cat, rname, sec, label, vals, conf, param in vendor_options:
        L.append(f'| {cat} | {esc(rname)} | {esc(sec)} | {esc(label) or "(no label)"} | {esc(vals)} | {esc(conf)} | {code(param)} |')
    if not vendor_options:
        L.append('| - | none | | | | | |')
    L += ['', '### 7.3 Show / hide / enable rules', '',
          '| Category | Report | Legacy: when | Legacy: effect | Evidence | In the new module |', '|---|---|---|---|---|---|']
    for cat, rname, when, effect, conf, new in rules:
        L.append(f'| {cat} | {esc(rname)} | {esc(when)} | {esc(effect)} | {esc(conf)} | {esc(new)} |')
    if not rules:
        L.append('| - | none | | | | |')
    L += ['', '### 7.4 Corrections to the screenshot inventory', '',
          '| Category | Report | About | Correction | Evidence |', '|---|---|---|---|---|']
    for cat, rname, about, text, conf in corrections:
        L.append(f'| {cat} | {esc(rname)} | {esc(about)} | {esc(text)} | {esc(conf)} |')
    if not corrections:
        L.append('| - | none | | | |')
    L.append('')

    L += ['## 8. Legacy screens to confirm on the live tool', '', '### 8.1 Criteria screens cut off by the screenshot (not resolved by vendor documentation)', '',
          '| Category | Report | What is cut off |', '|---|---|---|']
    for cat, name, notes in truncated:
        L.append(f'| {cat} | {esc(name)} | {esc(notes)} |')
    if not truncated:
        L.append('| - | none | |')
    L += ['', '### 8.2 Entries that could not be read with certainty', '', '| Category | Report | Section | Control | Notes |', '|---|---|---|---|---|']
    for cat, name, sec, label, notes in unreadable:
        L.append(f'| {cat} | {esc(name)} | {esc(sec)} | {esc(label) or "(no label)"} | {esc(notes)} |')
    if not unreadable:
        L.append('| - | none | | | |')
    L += ['', '### 8.3 Criteria questions the vendor documentation leaves open', '', '| Category | Report | Question |', '|---|---|---|']
    for cat, name, q in unresolved:
        L.append(f'| {cat} | {esc(name) or "(category)"} | {esc(q)} |')
    if not unresolved:
        L.append('| - | none | |')
    L.append('')
    open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'wrote {out}: categories={len(rows)} reports={tot["reports"]} controls={tot["controls"]} vendor_doc_controls={tot["vendor"]} '
          f'dynamic_rules={tot["rules"]} all_valid={all_valid} ' + ' '.join(f'{s}={tot[s]}' for s in STATUSES))
    return 0 if all_valid else 1


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    sys.exit(main(sys.argv[1], sys.argv[2], sys.argv[3]))
