"""Summarise the legacy criteria controls across all categories.

Usage: python -I summarize_controls.py <index_dir> <out_dir>

Reads <index_dir>/*.controls.json (from make_control_index.py) and writes:

  <out_dir>/control_patterns.md   readable summary: section titles, distinct control signatures, pickers,
                                  dropdowns, disabled controls, unreadable entries, truncated reports
  <out_dir>/signatures.json       every distinct control signature (section, type, label, options) with the
                                  control ids that share it - the unit the filter framework maps once

A "signature" is (section title, control type, label, option list) after whitespace normalisation, so the
same legacy control appearing on many reports is described once.
"""
import json
import os
import re
import sys
from collections import OrderedDict, defaultdict


def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def esc(s):
    return norm(s).replace('|', '\\|')


def main(index_dir, out_dir):
    cats = []
    for f in sorted(os.listdir(index_dir)):
        if f.endswith('.controls.json'):
            cats.append(json.load(open(os.path.join(index_dir, f), encoding='utf-8')))

    sigs = OrderedDict()          # signature key -> record
    sections = defaultdict(lambda: {'reports': set(), 'cats': set()})
    actions = defaultdict(int)
    truncated, unreadable, disabled = [], [], []
    n_reports = n_controls = 0
    for d in cats:
        cat = d['category']
        for r in d['reports']:
            n_reports += 1
            rname = f'{cat}: {r["name"]}'
            for a in r.get('actions', []):
                actions[norm(a)] += 1
            if r.get('possibly_truncated'):
                truncated.append((rname, norm(r.get('notes', ''))))
            for c in r['controls']:
                n_controls += 1
                sec = norm(c['section'])
                sections[sec]['reports'].add(rname)
                sections[sec]['cats'].add(cat)
                key = json.dumps([sec, c['type'], norm(c['label']), [norm(o) for o in c['options']]], ensure_ascii=False)
                rec = sigs.get(key)
                if rec is None:
                    rec = sigs[key] = {'section': sec, 'type': c['type'], 'label': norm(c['label']),
                                       'options': [norm(o) for o in c['options']], 'control_ids': [],
                                       'reports': [], 'defaults': defaultdict(int), 'disabled_ids': []}
                rec['control_ids'].append(c['control_id'])
                rec['reports'].append(rname)
                rec['defaults'][norm(c['default_value'])] += 1
                if not c.get('enabled', True):
                    rec['disabled_ids'].append(c['control_id'])
                    disabled.append((c['control_id'], rname, sec, norm(c['label']), norm(c['notes'])))
                text = ' '.join([c['label'], ' '.join(c['options']), c['default_value']])
                if '[?]' in text or '[?]' in sec:
                    unreadable.append((c['control_id'], rname, sec, norm(c['label']), norm(c['notes'])))

    sig_list = []
    for i, (key, rec) in enumerate(sigs.items(), 1):
        sig_list.append({
            'signature_id': f'sig{i:04d}',
            'section': rec['section'], 'type': rec['type'], 'label': rec['label'], 'options': rec['options'],
            'count': len(rec['control_ids']),
            'defaults': dict(rec['defaults']),
            'disabled_count': len(rec['disabled_ids']),
            'control_ids': rec['control_ids'],
        })
    os.makedirs(out_dir, exist_ok=True)
    json.dump({'report_count': n_reports, 'control_count': n_controls, 'signature_count': len(sig_list),
               'signatures': sig_list},
              open(os.path.join(out_dir, 'signatures.json'), 'w', encoding='utf-8'), indent=1, ensure_ascii=False)

    L = ['# Legacy criteria patterns (generated)', '',
         'Generated by `tools/summarize_controls.py` from `legacy/index/*.controls.json`. Do not edit by hand.', '',
         f'**Totals:** {len(cats)} categories, {n_reports} reports, {n_controls} controls, '
         f'{len(sig_list)} distinct control signatures '
         f'({sum(1 for s in sig_list if s["count"] > 1)} used by more than one report, '
         f'covering {sum(s["count"] for s in sig_list if s["count"] > 1)} controls).', '']

    L += ['## 1. Section titles', '', '| Section title | Reports | Categories |', '|---|---|---|']
    for sec, v in sorted(sections.items(), key=lambda kv: (-len(kv[1]['reports']), kv[0])):
        L.append(f'| {esc(sec)} | {len(v["reports"])} | {", ".join(sorted(v["cats"]))} |')
    L.append('')

    L += ['## 2. Control signatures by section', '',
          'One row per distinct (section, type, label, options). "Defaults" shows each default value seen and how often.', '']
    by_sec = defaultdict(list)
    for s in sig_list:
        by_sec[s['section']].append(s)
    for sec, v in sorted(sections.items(), key=lambda kv: (-len(kv[1]['reports']), kv[0])):
        L += [f'### {sec}  ({len(v["reports"])} reports)', '',
              '| Signature | Type | Label | Options | Defaults | Uses | Disabled | Example reports |', '|---|---|---|---|---|---|---|---|']
        for s in sorted(by_sec[sec], key=lambda x: -x['count']):
            rec = sigs[json.dumps([s['section'], s['type'], s['label'], s['options']], ensure_ascii=False)]
            ex = '; '.join(list(OrderedDict.fromkeys(rec['reports']))[:3])
            dv = '; '.join(f'{esc(k) or "(empty)"} x{n}' for k, n in s['defaults'].items())
            L.append(f'| {s["signature_id"]} | {s["type"]} | {esc(s["label"]) or "(no label)"} | '
                     f'{" / ".join(esc(o) for o in s["options"]) or "-"} | {dv} | {s["count"]} | '
                     f'{s["disabled_count"] or "-"} | {esc(ex)} |')
        L.append('')

    L += ['## 3. Global action buttons', '', '| Action | Reports |', '|---|---|']
    for a, n in sorted(actions.items(), key=lambda kv: -kv[1]):
        L.append(f'| {esc(a)} | {n} |')
    L.append('')

    for title, kind in (('4. Pickers', 'picker'), ('5. Dropdowns', 'dropdown'), ('6. Buttons inside the criteria area', 'button'),
                        ('7. Static text', 'static_text'), ('8. Other controls', 'other')):
        rows = [s for s in sig_list if s['type'] == kind]
        L += [f'## {title}', '', '| Signature | Section | Label | Options | Defaults | Uses |', '|---|---|---|---|---|---|']
        for s in sorted(rows, key=lambda x: (x['label'].lower(), x['section'])):
            dv = '; '.join(f'{esc(k) or "(empty)"} x{n}' for k, n in s['defaults'].items())
            L.append(f'| {s["signature_id"]} | {esc(s["section"])} | {esc(s["label"]) or "(no label)"} | '
                     f'{" / ".join(esc(o) for o in s["options"]) or "-"} | {dv} | {s["count"]} |')
        L.append('')

    L += ['## 9. Controls captured greyed out (disabled)', '', '| Control id | Report | Section | Label | Notes |', '|---|---|---|---|---|']
    for cid, rname, sec, label, notes in disabled:
        L.append(f'| {cid} | {esc(rname)} | {esc(sec)} | {esc(label) or "(no label)"} | {esc(notes)} |')
    L.append('')
    L += ['## 10. Entries not fully readable ("[?]")', '', '| Control id | Report | Section | Label | Notes |', '|---|---|---|---|---|']
    for cid, rname, sec, label, notes in unreadable:
        L.append(f'| {cid} | {esc(rname)} | {esc(sec)} | {esc(label) or "(no label)"} | {esc(notes)} |')
    L.append('')
    L += ['## 11. Reports whose criteria screen is cut off in the screenshot', '', '| Report | Notes |', '|---|---|']
    for rname, notes in truncated:
        L.append(f'| {esc(rname)} | {esc(notes)} |')
    L.append('')
    open(os.path.join(out_dir, 'control_patterns.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'reports={n_reports} controls={n_controls} signatures={len(sig_list)} '
          f'recurring={sum(1 for s in sig_list if s["count"] > 1)} '
          f'controls_in_recurring={sum(s["count"] for s in sig_list if s["count"] > 1)} '
          f'sections={len(sections)} disabled={len(disabled)} unreadable={len(unreadable)} truncated={len(truncated)}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
