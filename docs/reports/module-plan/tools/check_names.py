"""Cross-document name check: every name one document uses must be defined by the document that owns it.

Usage: python -I check_names.py <plan_root> [--max N]

Checks (each prints the undefined names with the places that use them):

  1. rpt_* datasets        owner 03_data_foundation.md            used anywhere else
  2. report_* tables       owner 02_architecture.md               used anywhere else
  3. API paths             owner 02_architecture.md               /api/v1/reports/... and /api/v1/analytics/... used elsewhere
  4. work-item ids         owner: the document that defines them  ENG-01, DATA-13, RPT-DAILY-12 ... used anywhere
  5. report keys           owner catalog/parity/*.parity.json and catalog/analytics_reports.md
                           `category.report_name` used anywhere
  6. metric keys           owner 05_metric_catalog.md             metric-like names used in 06_dashboards.md and the catalog
  7. brief decisions       owner 00_design_brief.md               AD-n / PD-n used anywhere
  8. parameter keys        owner legacy/index/signature_map.json and catalog/decisions/*.json
                           parameter keys of the parity files that the shared dictionary does not list (information)

Writes <plan_root>/name_check.md with the full lists and prints a summary. Exit code is always 0: the output
is a work list for the consistency pass, not a gate.
"""
import json
import os
import re
import sys
from collections import defaultdict

CAT_PREFIXES = ['daily', 'monthly', 'ledger', 'management', 'insurance', 'appointment', 'treatment_plan', 'referral', 'recall',
                'ortho', 'statements', 'lists', 'my_reports', 'worklists', 'custom', 'analytics', 'dashboards']
WI_RE = re.compile(r'\b((?:ENG|DATA|FLT|MET|DASH|UX|SEC|RPT-[A-Z]{2,8})-\d{1,3}[a-z]?)\b')
RPT_RE = re.compile(r'\b(rpt_[a-z0-9_]+)\b')
TBL_RE = re.compile(r'\b(report_[a-z0-9_]+)\b')
API_RE = re.compile(r'(/api/v1/(?:reports|analytics)[A-Za-z0-9_\-/{}.]*)')
KEY_RE = re.compile(r'`((?:' + '|'.join(CAT_PREFIXES) + r')\.[a-z0-9][a-z0-9_]*)`')
DEC_RE = re.compile(r'\b((?:AD|PD)-\d{1,2})\b')
TICK_RE = re.compile(r'`([a-z][a-z0-9_]{3,})`')
METRIC_HINT = re.compile(r'(_pct|_rate|_ratio|_count|_amount|_production|_collections?|_per_[a-z_]+|_days|_hours|_avg|_average|_total|_balance|_ar|_writeoffs?)$')


def read(path):
    try:
        return open(path, encoding='utf-8').read()
    except OSError:
        return ''


def uses(docs, regex, norm=lambda x: x):
    out = defaultdict(lambda: defaultdict(list))
    for rel, text in docs.items():
        for n, line in enumerate(text.splitlines(), 1):
            for m in regex.finditer(line):
                out[norm(m.group(1))][rel].append(n)
    return out


def norm_api(p):
    p = re.sub(r'\{[^}]*\}', '{}', p.rstrip('/.,;:)'))
    return p


def section(L, title, undefined, limit):
    L += ['', f'## {title}', '']
    if not undefined:
        L.append('None.')
        return
    L += ['| Name | Used in (line numbers) |', '|---|---|']
    for name in sorted(undefined)[:limit]:
        where = '; '.join(f'{rel}: {", ".join(str(n) for n in lines[:6])}{" ..." if len(lines) > 6 else ""}' for rel, lines in sorted(undefined[name].items()))
        L.append(f'| `{name}` | {where} |')
    if len(undefined) > limit:
        L.append(f'| ... | {len(undefined) - limit} more |')


def main(root, limit):
    names = sorted(f for f in os.listdir(root) if re.match(r'^\d\d_.*\.md$', f) and not f.startswith(('01_', '09_')))
    names += ['README.md'] if os.path.exists(os.path.join(root, 'README.md')) else []
    cat_dir = os.path.join(root, 'catalog')
    names += sorted('catalog/' + f for f in os.listdir(cat_dir) if f.endswith('.md')) if os.path.isdir(cat_dir) else []
    docs = {rel: read(os.path.join(root, rel)) for rel in names}
    L = ['# Cross-document name check', '', 'Generated by `tools/check_names.py`. Each list is a name that a document uses but its owner does not define.', '']
    summary = []

    # 1 datasets
    own = set(RPT_RE.findall(docs.get('03_data_foundation.md', '')))
    used = uses({k: v for k, v in docs.items() if k != '03_data_foundation.md'}, RPT_RE)
    und = {k: v for k, v in used.items() if k not in own and not k.endswith('_') and k not in ('rpt_', 'rpt_x')}
    section(L, '1. rpt_* names not defined in 03_data_foundation.md', und, limit)
    summary.append(('undefined rpt_* names', len(und)))

    # 2 engine tables
    own = set(TBL_RE.findall(docs.get('02_architecture.md', '')))
    used = uses({k: v for k, v in docs.items() if k != '02_architecture.md'}, TBL_RE)
    und = {k: v for k, v in used.items() if k not in own and not k.endswith('_')
           and k not in ('report_key', 'report_keys', 'report_format', 'report_type', 'report_id', 'report_by', 'report_name', 'report_date',
                         'report_access_provider_id', 'report_category', 'report_title', 'report_count')}
    section(L, '2. report_* names not found in 02_architecture.md', und, limit)
    summary.append(('undefined report_* names', len(und)))

    # 3 API paths
    own = {norm_api(p) for p in API_RE.findall(docs.get('02_architecture.md', ''))}
    used = uses({k: v for k, v in docs.items() if k != '02_architecture.md'}, API_RE, norm_api)
    und = {k: v for k, v in used.items() if k not in own and not any(o.startswith(k) for o in own)}
    section(L, '3. API paths not found in 02_architecture.md', und, limit)
    summary.append(('undefined API paths', len(und)))

    # 4 work items
    reg_path = os.path.join(root, 'work_items.json')
    reg = {it['id'] for it in json.load(open(reg_path, encoding='utf-8'))['items']} if os.path.exists(reg_path) else set()
    used = uses(docs, WI_RE)
    und = {k: v for k, v in used.items() if k not in reg} if reg else {}
    section(L, '4. Work-item ids that no document defines (run collect_work_items.py first)', und, limit)
    summary.append(('undefined work-item ids', len(und)))

    # 5 report keys
    keys = set()
    par_dir = os.path.join(root, 'catalog', 'parity')
    if os.path.isdir(par_dir):
        for f in os.listdir(par_dir):
            if f.endswith('.parity.json'):
                for r in json.load(open(os.path.join(par_dir, f), encoding='utf-8')).get('reports', []):
                    keys.add(r.get('report_key', ''))
    new_doc = docs.get('catalog/analytics_reports.md', '')
    for m in re.finditer(r'^#{2,3} .*`([a-z_]+\.[a-z0-9_]+)`', new_doc, flags=re.M):
        keys.add(m.group(1))
    dash = docs.get('06_dashboards.md', '')
    for m in re.finditer(r'^\|\s*`((?:dashboards|worklists)\.[a-z0-9_]+)`\s*\|', dash, flags=re.M):
        keys.add(m.group(1))
    used = uses(docs, KEY_RE)
    und = {k: v for k, v in used.items() if k not in keys
           and k.rsplit('.', 1)[1] not in ('py', 'md', 'json', 'ts', 'tsx', 'js', 'sql', 'csv', 'pdf', 'xlsx', 'html', 'yaml', 'yml')}
    section(L, '5. report keys that are neither a legacy report (parity files) nor a new report (catalog/analytics_reports.md, 06_dashboards.md)', und, limit)
    summary.append(('undefined report keys', len(und)))

    # 6 metric keys
    met = docs.get('05_metric_catalog.md', '')
    own = set(re.findall(r'^\|\s*`([a-z][a-z0-9_]+)`\s*\|', met, flags=re.M)) | set(TICK_RE.findall(met))
    other = set(TICK_RE.findall(docs.get('03_data_foundation.md', ''))) | set(TICK_RE.findall(docs.get('04_filter_framework.md', ''))) \
        | set(TICK_RE.findall(docs.get('02_architecture.md', '')))
    used = uses({k: v for k, v in docs.items() if k == '06_dashboards.md' or k.startswith('catalog/')}, TICK_RE)
    und = {k: v for k, v in used.items() if METRIC_HINT.search(k) and k not in own and k not in other} if met else {}
    section(L, '6. Metric-like names used in 06_dashboards.md or the catalog that 05_metric_catalog.md does not define (heuristic: review each)', und, limit)
    summary.append(('possibly undefined metric keys', len(und)))

    # 7 brief decisions
    own = set(DEC_RE.findall(docs.get('00_design_brief.md', '')))
    used = uses({k: v for k, v in docs.items() if k != '00_design_brief.md'}, DEC_RE)
    und = {k: v for k, v in used.items() if k not in own}
    section(L, '7. AD-n / PD-n references that 00_design_brief.md does not define', und, limit)
    summary.append(('undefined brief decisions', len(und)))

    # 8 parameter keys
    shared = set()
    sm = os.path.join(root, 'legacy', 'index', 'signature_map.json')
    if os.path.exists(sm):
        d = json.load(open(sm, encoding='utf-8'))
        for k, v in (d.get('parameters') or {}).items():
            shared.add(k)
            for kk in (v.get('keys') or []) if isinstance(v, dict) else []:
                shared.add(kk)
        for m in d.get('mappings', []):
            if m.get('param'):
                shared.add(m['param'])
    extra = defaultdict(lambda: defaultdict(list))
    if os.path.isdir(par_dir):
        for f in sorted(os.listdir(par_dir)):
            if f.endswith('.parity.json'):
                for r in json.load(open(os.path.join(par_dir, f), encoding='utf-8')).get('reports', []):
                    for c in r.get('controls', []):
                        p = c.get('param') or ''
                        if p and p not in shared and p.split('.')[0] not in shared:
                            extra[p][r.get('report_key') or r.get('report_id')].append(c.get('control_id', '').rsplit('.', 2)[-2] if c.get('control_id') else 0)
    L += ['', '## 8. Report-specific parameter keys (not in the shared dictionary) - information', '']
    if extra:
        L += ['| Parameter | Reports |', '|---|---|']
        for p in sorted(extra):
            L.append(f'| `{p}` | {", ".join(sorted(extra[p]))} |')
    else:
        L.append('None.')
    summary.append(('report-specific parameter keys (information)', len(extra)))

    open(os.path.join(root, 'name_check.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'documents scanned: {len(docs)}')
    for k, v in summary:
        print(f'  {k}: {v}')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    lim = 400
    if '--max' in sys.argv:
        lim = int(sys.argv[sys.argv.index('--max') + 1])
    main(sys.argv[1], lim)
